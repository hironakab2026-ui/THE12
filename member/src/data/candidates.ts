/** 再現性のあるダミー票（同じ候補はいつも同じ数） */
const seedFor = (teamIndex: number, i: number): number => [412, 287, 158][i] + ((teamIndex * 37 + i * 53) % 120);

export const CANDIDATES: Candidate[] = TEAMS.flatMap((t, ti) =>
  (ROWS[t.id] ?? []).map(([name, no, pos, intro], i) => ({
    id: `${t.id}-${i + 1}`,
    team: t.id,
    name,
    no,
    pos,
    intro,
    seed: seedFor(ti, i),
  })),
);

export const findCandidate = (id: string): Candidate | undefined => CANDIDATES.find((c) => c.id === id);
export const candidatesOf = (team: string): Candidate[] => CANDIDATES.filter((c) => c.team === team);

/** 今年のTHE 12（各球団の1人目をデモ上の現メンバーとする） */
export const CURRENT_12: Candidate[] = TEAMS.map((t) => candidatesOf(t.id)[0]);
